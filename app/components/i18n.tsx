export type MessageKey = keyof typeof messages.vi;

type I18nContext = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey) => string;
};

const LocaleContext = createContext<I18nContext | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("vi");

  useEffect(() => {
    const saved = window.localStorage.getItem("skillbridge-locale");
    if (saved !== "vi" && saved !== "en") return;
    const timer = window.setTimeout(() => setLocaleState(saved), 0);
    return () => window.clearTimeout(timer);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.cookie = `skillbridge-locale=${locale};path=/;max-age=31536000;samesite=lax`;
  }, [locale]);

  const value = useMemo<I18nContext>(() => ({
    locale,
    setLocale(nextLocale) {
      window.localStorage.setItem("skillbridge-locale", nextLocale);
      setLocaleState(nextLocale);
    },
    t(key) {
      return messages[locale][key] ?? messages.vi[key] ?? key;
    },
  }), [locale]);

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LocaleContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}

const statusKeys: Record<string, MessageKey> = {
  draft: "status.draft", published: "status.published", submitted: "status.submitted", in_review: "status.inReview",
  changes_requested: "status.changesRequested", approved: "status.approved", issued: "status.issued", active: "status.active",
  revoked: "status.revoked", verified: "status.verified", pending: "status.pending", public: "status.public", invite_only: "status.inviteOnly",
  not_joined: "status.notJoined", closed: "status.closed", locked: "status.locked", unlocked: "status.unlocked",
  ready: "status.ready", waiting: "status.waiting", empty: "status.empty", missing: "status.missing", valid: "status.valid", not_sent: "status.notSent", "not sent": "status.notSent",
};

export function translateStatus(t: (key: MessageKey) => string, value: string | null | undefined) {
  if (!value) return "—";
  return statusKeys[value] ? t(statusKeys[value]) : value.replaceAll("_", " ");
}

export function LanguageSwitcher() {
  const { locale, setLocale, t } = useLanguage();
  return (
    <div className="language-switcher" aria-label={t("common.language")}>
      <button className={locale === "vi" ? "active" : ""} onClick={() => setLocale("vi")} type="button">VI</button>
      <span aria-hidden="true">/</span>
      <button className={locale === "en" ? "active" : ""} onClick={() => setLocale("en")} type="button">EN</button>
    </div>
  );
}
